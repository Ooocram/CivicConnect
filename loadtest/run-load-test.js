// loadtest/run-load-test.js
// TASK C: performance/load exercise on the most sensitive public operation,
// POST /api/v1/requests (FR-01). Why this endpoint: it is unauthenticated (anyone can call it),
// it WRITES to the database inside a transaction, and so it is the first thing a traffic spike
// or abuse (STRIDE "Denial of Service") would hit.
//
// What this script does, in order:
//   1. starts the API as a SEPARATE process against the TEST database (never the dev DB);
//   2. warms it up (discarded), then runs one autocannon stage per concurrency level;
//   3. after every stage, counts rows in the DB and compares them with the 2xx responses
//      (data-integrity-under-load check: no lost or phantom writes);
//   4. prints a Markdown results table and saves .json + .md reports in loadtest/results/.
//
// Usage:   npm run loadtest
// Tuning (optional env vars):
//   LOAD_DURATION=15        seconds per stage          LOAD_STAGES=1,10,50,100   concurrent connections
//   LOAD_PORT=3500          port for the temp server   DB_POOL_MAX=5             DB pool size under test
const path = require('path');
const fs = require('fs');
const os = require('os');
const { spawn } = require('child_process');

require('../tests/setup/env'); // sets NODE_ENV=test and REFUSES to run unless the DB is a *test* DB
const autocannon = require('autocannon');
const { sequelize } = require('../src/persistence/models');

// ---------------- Test design (document these in the PED) ----------------------------------
const PORT = Number(process.env.LOAD_PORT) || 3500;
const DURATION_S = Number(process.env.LOAD_DURATION) || 15;
const STAGES = (process.env.LOAD_STAGES || '1,10,50,100').split(',').map(Number);
const POOL_MAX = Number(process.env.DB_POOL_MAX) || 5;
const EXPECTED_PEAK = 50; // ASSUMPTION: peak concurrent submissions for a municipal portal. Stages above it are STRESS (informational).
const ACCEPT = {
  maxErrorRate: 0,   // no failed requests at or below expected peak
  p97_5Ms: 500,      // latency; autocannon reports p97.5, a stricter stand-in for "p95 <= 500 ms"
  zeroLostWrites: true, // every 2xx response has a saved row (rows >= 2xx); surplus rows <= connections (requests still in flight when the timer stopped)
};
const PAYLOAD = {
  title: 'Load test: pothole on Main St',
  description: 'Synthetic request generated by the Task C load test.',
  location: 'Main St',
};
const URL = `http://127.0.0.1:${PORT}/api/v1/requests`;
// ---------------------------------------------------------------------------------------------

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const rowCount = async () => (await sequelize.query('SELECT count(*)::int AS n FROM "ServiceRequests"', { type: 'SELECT' }))[0].n;
const clean = () => sequelize.query('TRUNCATE "Comments", "ServiceRequests" RESTART IDENTITY CASCADE');

async function startServer() {
  const child = spawn(process.execPath, ['server.js'], {
    cwd: path.resolve(__dirname, '..'),
    env: { ...process.env, NODE_ENV: 'test', PORT: String(PORT) },
    stdio: ['ignore', 'ignore', 'pipe'],
  });
  let stderr = '';
  child.stderr.on('data', (d) => { stderr += d; });
  for (let i = 0; i < 50; i++) { // wait until it answers (an empty body gets a 400 = server is up)
    if (child.exitCode !== null) throw new Error('Server exited early:\n' + stderr);
    try {
      const r = await fetch(URL, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{}' });
      if (r.status === 400) return child;
    } catch { /* not up yet */ }
    await sleep(200);
  }
  child.kill();
  throw new Error('Server did not become ready:\n' + stderr);
}

const fire = (connections, duration) => autocannon({
  url: URL, method: 'POST', connections, duration, timeout: 10,
  headers: { 'content-type': 'application/json' },
  body: JSON.stringify(PAYLOAD),
});

function judge(c, r) {
  const gated = c <= EXPECTED_PEAK;
  const reasons = [];
  if (r.errorRate > ACCEPT.maxErrorRate) reasons.push(`errors ${(r.errorRate * 100).toFixed(2)}%`);
  if (r.p97_5 > ACCEPT.p97_5Ms) reasons.push(`p97.5 ${r.p97_5} ms > ${ACCEPT.p97_5Ms}`);
  const lost = r.ok - r.rowsSaved;      // acknowledged (2xx) but NOT stored = real data loss
  const surplus = r.rowsSaved - r.ok;   // stored but response not counted: only requests in flight when the timer stopped
  if (lost > 0) reasons.push(`${lost} lost writes`);
  if (surplus > c) reasons.push(`${surplus} unexplained extra rows (> ${c} in flight)`);
  if (!reasons.length) return { gated, verdict: 'PASS' };
  return { gated, verdict: gated ? 'FAIL' : 'DEGRADED (stress)', reasons };
}

(async () => {
  const server = await startServer();
  const rows = [];
  try {
    await fire(10, 3); // warm-up: JIT, DB pool and caches; result discarded
    for (const c of STAGES) {
      await clean();
      const res = await fire(c, DURATION_S);
      const ok = res['2xx'];
      const failed = res.non2xx + res.errors + res.timeouts;
      const total = ok + failed;
      const row = {
        connections: c, reqPerSec: Math.round(res.requests.average), totalRequests: total, ok, failed,
        errorRate: total ? failed / total : 0,
        p50: res.latency.p50, p90: res.latency.p90, p97_5: res.latency.p97_5, p99: res.latency.p99, max: res.latency.max,
        meanMs: Number(res.latency.average.toFixed(1)),
        rowsSaved: await rowCount(),
      };
      Object.assign(row, judge(c, row));
      rows.push(row);
      console.log(`  stage ${String(c).padStart(3)} conn: ${row.reqPerSec} req/s, p97.5 ${row.p97_5} ms, failed ${failed}, ${row.verdict}`);
      await sleep(1500); // let the server drain between stages
    }
  } finally {
    server.kill();
    await clean();
    await sequelize.close();
  }

  // ---- reports ----
  const env = {
    when: new Date().toISOString(), node: process.version, os: `${os.platform()} ${os.release()}`,
    cpu: `${os.cpus().length} x ${os.cpus()[0].model.trim()}`, ramGB: Math.round(os.totalmem() / 1e9),
    dbPoolMax: POOL_MAX, stageDurationSeconds: DURATION_S, endpoint: 'POST /api/v1/requests',
    note: 'Load generator, API and PostgreSQL ran on the SAME machine and compete for CPU.',
  };
  const md = [
    `### Load test results – POST /api/v1/requests (pool max ${POOL_MAX}, ${DURATION_S}s per stage)`,
    '',
    '| Connections | Req/s | Mean ms | p50 ms | p90 ms | p97.5 ms | p99 ms | Max ms | OK (2xx) | Failed | Rows saved | Verdict |',
    '|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|',
    ...rows.map((r) => `| ${r.connections} | ${r.reqPerSec} | ${r.meanMs} | ${r.p50} | ${r.p90} | ${r.p97_5} | ${r.p99} | ${r.max} | ${r.ok} | ${r.failed} | ${r.rowsSaved} | ${r.verdict} |`),
    '',
    `Acceptance thresholds (stages <= ${EXPECTED_PEAK} connections): error rate ${ACCEPT.maxErrorRate * 100}%, p97.5 <= ${ACCEPT.p97_5Ms} ms, no lost writes (every 2xx has a saved row; rows may exceed 2xx by at most the connection count = requests in flight when the timer stopped).`,
    `Environment: ${env.cpu}, ${env.ramGB} GB RAM, ${env.os}, Node ${env.node}. ${env.note}`,
  ].join('\n');
  console.log('\n' + md);

  const stamp = env.when.replace(/[:.]/g, '-');
  const base = path.join(__dirname, 'results', `loadtest-pool${POOL_MAX}-${stamp}`);
  fs.mkdirSync(path.dirname(base), { recursive: true });
  fs.writeFileSync(base + '.json', JSON.stringify({ env, thresholds: ACCEPT, expectedPeak: EXPECTED_PEAK, rows }, null, 2));
  fs.writeFileSync(base + '.md', md + '\n');
  console.log(`\nSaved: ${path.relative(process.cwd(), base)}.json / .md`);

  if (rows.some((r) => r.gated && r.verdict === 'FAIL')) process.exitCode = 1;
})().catch((e) => { console.error(e); process.exit(1); });
